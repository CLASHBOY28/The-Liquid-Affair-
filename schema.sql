-- The Liquid Affair inventory database
create table if not exists categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists inventory_items (
  id bigint generated by default as identity primary key,
  name text not null,
  category_id bigint references categories(id) on delete set null,
  quantity integer not null default 0 check (quantity >= 0),
  reorder_threshold integer not null default 5 check (reorder_threshold >= 0),
  unit text not null default 'pcs',
  expiry_date date,
  updated_at timestamptz not null default now(),
  unique (name, category_id)
);

create table if not exists inventory_audit (
  id bigint generated by default as identity primary key,
  item_name text,
  action text not null,
  old_quantity integer,
  new_quantity integer,
  note text,
  created_at timestamptz not null default now()
);

create index if not exists inventory_items_category_idx on inventory_items(category_id);
create index if not exists inventory_items_name_idx on inventory_items(name);
create index if not exists inventory_audit_created_at_idx on inventory_audit(created_at desc);

alter table categories enable row level security;
alter table inventory_items enable row level security;
alter table inventory_audit enable row level security;

