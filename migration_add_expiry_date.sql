-- Run once in Supabase SQL Editor to enable expiry dates and flexible inventory columns.
alter table public.inventory_items
  add column if not exists expiry_date date,
  add column if not exists custom_values jsonb not null default '{}'::jsonb;

create index if not exists inventory_items_expiry_date_idx
  on public.inventory_items(expiry_date)
  where expiry_date is not null;

create table if not exists public.inventory_custom_fields (
  id bigint generated by default as identity primary key,
  name text not null unique,
  field_type text not null default 'text'
    check (field_type in ('text', 'number', 'date')),
  position integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.inventory_custom_fields enable row level security;
-- The app uses the private server-side Supabase service-role key.
