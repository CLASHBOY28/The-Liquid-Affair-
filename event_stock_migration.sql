-- Run once in Supabase Dashboard > SQL Editor before using Event Stock.
create table if not exists event_stock_events (
  id bigint generated by default as identity primary key,
  name text not null unique,
  columns jsonb not null default '["Item","Quantity","Unit","Notes"]'::jsonb,
  rows jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists event_stock_events_created_at_idx on event_stock_events(created_at desc);
alter table event_stock_events enable row level security;
-- No anonymous policies. The private server accesses this table with SUPABASE_SERVICE_ROLE_KEY.
